  function hasSection(airline, title) {
    return airline.sections && airline.sections.some(section => section.title === title);
  }

  Object.entries(standardAdditions).forEach(([slug, additions]) => {
    const airline = window.AIRLINE_DATA[slug];
    if (!airline) return;
    if (!Array.isArray(airline.sections)) airline.sections = [];

    const summaryIndex = airline.sections.findIndex(section => section.title.includes("מסכמת"));
    const insertIndex = summaryIndex >= 0 ? summaryIndex : airline.sections.length;

    additions.forEach(addition => {
      if (!hasSection(airline, addition.title)) {
        airline.sections.splice(insertIndex, 0, addition);
      }
    });
  });
